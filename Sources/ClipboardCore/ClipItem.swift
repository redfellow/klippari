import CryptoKit
import Foundation

/// Raw pasteboard type strings the app cares about by name.
public enum TypeName {
    public static let plainText = "public.utf8-plain-text"
    public static let rtf = "public.rtf"
    public static let html = "public.html"
    public static let fileURL = "public.file-url"
    public static let png = "public.png"
    public static let tiff = "public.tiff"

    /// The only types whose bytes history items keep in memory: what the
    /// panel shows and searches. Everything else stays on disk until pasted.
    public static let keptInMemory: Set<String> = [plainText, fileURL]

    /// nspasteboard.org markers: content carrying any of these is never recorded.
    public static let skipMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        // Older markers that predate the nspasteboard.org convention and
        // are still set by some password managers and text expanders.
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]
}

/// One representation of a pasteboard item. `data` is nil only on a raw
/// read where the source app could not supply the bytes.
public struct TypedData: Equatable, Sendable {
    public var type: String
    public var data: Data?

    public init(type: String, data: Data?) {
        self.type = type
        self.data = data
    }
}

/// One NSPasteboardItem: the same thing in several representations.
public struct PasteboardEntry: Equatable, Sendable {
    public var types: [TypedData]

    public init(types: [TypedData]) {
        self.types = types
    }
}

/// Everything that was on the pasteboard after one copy.
public struct ClipContent: Equatable, Sendable {
    public var entries: [PasteboardEntry]

    public init(entries: [PasteboardEntry]) {
        self.entries = entries
    }

    public var totalBytes: Int {
        entries.reduce(0) { sum, entry in
            sum + entry.types.reduce(0) { $0 + ($1.data?.count ?? 0) }
        }
    }

    /// SHA-256 over every (type, byte count, bytes) in order. Lengths are
    /// hashed so that moving bytes between a type name and its data, or
    /// between neighbouring types, changes the hash.
    public var contentHash: String {
        var hasher = SHA256()
        func feed(_ count: Int) {
            var value = UInt64(count).littleEndian
            withUnsafeBytes(of: &value) { hasher.update(bufferPointer: $0) }
        }
        feed(entries.count)
        for entry in entries {
            feed(entry.types.count)
            for typed in entry.types {
                let name = Data(typed.type.utf8)
                feed(name.count)
                hasher.update(data: name)
                let data = typed.data ?? Data()
                feed(data.count)
                hasher.update(data: data)
            }
        }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }

    public func data(for type: String) -> Data? {
        for entry in entries {
            if let match = entry.types.first(where: { $0.type == type }), let data = match.data {
                return data
            }
        }
        return nil
    }

    /// True when some entry has this type, whether or not its bytes are
    /// in memory.
    public func hasType(_ type: String) -> Bool {
        entries.contains { entry in entry.types.contains { $0.type == type } }
    }

    /// False for a lightened copy, which cannot be pasted or saved.
    public var isComplete: Bool {
        entries.allSatisfy { entry in entry.types.allSatisfy { $0.data != nil } }
    }

    /// The same types, with bytes kept only for text and file URLs. This
    /// is what the history holds in memory, so that images and other
    /// large data stay on disk.
    public var lightened: ClipContent {
        ClipContent(entries: entries.map { entry in
            PasteboardEntry(types: entry.types.map { typed in
                TypeName.keptInMemory.contains(typed.type) ? typed : TypedData(type: typed.type, data: nil)
            })
        })
    }

    /// What to put on the pasteboard when this content is pasted as copied.
    ///
    /// Browsers copy an image as its bytes plus an HTML fragment that is
    /// just an <img> tag pointing at the remote original. Rich text views
    /// such as Notes prefer the HTML, and the system's HTML importer then
    /// fetches that URL synchronously; when the server does not answer,
    /// the app being pasted into hangs. Since the real image bytes are
    /// here, the HTML wrapper is left out. HTML is kept whenever the copy
    /// also has text, where it carries real formatting.
    public var forPasting: ClipContent {
        let hasImage = hasType(TypeName.png) || hasType(TypeName.tiff)
        guard hasImage, !hasType(TypeName.plainText), hasType(TypeName.html) else { return self }
        return ClipContent(entries: entries.map { entry in
            PasteboardEntry(types: entry.types.filter { $0.type != TypeName.html })
        })
    }

    public var plainString: String? {
        data(for: TypeName.plainText).flatMap { String(data: $0, encoding: .utf8) }
    }

    public var fileURLs: [URL] {
        entries.compactMap { entry in
            entry.types.first(where: { $0.type == TypeName.fileURL })?.data
                .flatMap { String(data: $0, encoding: .utf8) }
                .flatMap { URL(string: $0) }
        }
    }

    /// The same content reduced to its plain string, for pasting without
    /// styling. Nil when there is no text form.
    public var plainTextOnly: ClipContent? {
        guard let string = plainString else { return nil }
        return ClipContent(entries: [
            PasteboardEntry(types: [TypedData(type: TypeName.plainText, data: Data(string.utf8))]),
        ])
    }
}

/// One remembered copy.
public struct ClipItem: Identifiable, Equatable, Sendable {
    public let id: UUID
    public var capturedAt: Date
    public var lastUsedAt: Date
    /// Name of the app that was frontmost at capture; nil when unknown.
    public var sourceApp: String?
    /// In the history this is a lightened copy; the full bytes are on disk.
    public var content: ClipContent
    public var imageInfo: ImageInfo?
    /// Hash of the full content, computed once when the item is created.
    public let contentHash: String
    /// Set for a secret: it is kept in memory only, with its full content,
    /// and leaves the history at this time. Nil for ordinary items.
    public var expiresAt: Date?

    public var isSecret: Bool { expiresAt != nil }

    /// Pass `contentHash` when `content` is a lightened copy; otherwise it
    /// is computed from `content`.
    public init(
        id: UUID, capturedAt: Date, lastUsedAt: Date, sourceApp: String?,
        content: ClipContent, imageInfo: ImageInfo?, contentHash: String? = nil, expiresAt: Date? = nil
    ) {
        self.id = id
        self.capturedAt = capturedAt
        self.lastUsedAt = lastUsedAt
        self.sourceApp = sourceApp
        self.content = content
        self.imageInfo = imageInfo
        self.contentHash = contentHash ?? content.contentHash
        self.expiresAt = expiresAt
    }
}
